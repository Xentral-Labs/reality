"""Key every company-scoped table by its company.

PostgreSQL will not partition a table unless every unique constraint contains the
partition key, the primary key included — and every one of these tables was keyed
by `id` alone. Spec 181 FR-005 asks for tables that *can* be partitioned by
company, and this is the change that makes them so: the key becomes
`(tenant_id, id)`, in that order, which is also the better index in a system where
every read names a company.

A foreign key in PostgreSQL binds to an index rather than to columns, so the old
key cannot simply be replaced underneath one. Every reference that pointed at
`id` alone is therefore dropped and made again over `(tenant_id, parent_id)` —
106 of them. That is not merely the cost of the change, it is most of
its value: a row can no longer name a parent belonging to another company, and the
database is what refuses it. Four tests existed only to prove the readers caught
such rows; they now prove the schema will not hold them.

`security_audit_event` is deliberately left alone. A signup, an admission and a
failed login happen before there is a company, and that is where they are written,
so its company column is nullable and cannot be part of a key.

The foreign-key index rule moves with it (`index_foreign_keys`): it indexes the
whole key rather than its first column, because the first column is now the
company on every one of these. Asking only about the first column would have found
`tenant_id` already indexed and quietly left 190 references unindexed —
`business_event.causation_id` among them, the one that took a company deletion from
thirty-six minutes to under four seconds.

Revision ID: 0088_tenant_scoped_keys
Revises: 0087_cost_conversion
"""

