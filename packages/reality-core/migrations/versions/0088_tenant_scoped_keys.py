def _constraint_name(table: str, columns: tuple[str, ...], target: str) -> str | None:
    """What this database calls that reference, or None if it does not have it."""
    row = (
        op.get_bind()
        .exec_driver_sql(
            """
        SELECT con.conname
          FROM pg_constraint con
          JOIN pg_class child ON child.oid = con.conrelid
          JOIN pg_class parent ON parent.oid = con.confrelid
         WHERE con.contype = 'f'
           AND child.relname = %s
           AND parent.relname = %s
           AND (
                 SELECT array_agg(a.attname ORDER BY k.ord)
                   FROM unnest(con.conkey) WITH ORDINALITY k(attnum, ord)
                   JOIN pg_attribute a
                     ON a.attrelid = con.conrelid AND a.attnum = k.attnum
               ) = %s::name[]
        """,
            (table, target, list(columns)),
        )
        .first()
    )
    return row[0] if row else None


def upgrade() -> None:
    # Order matters and is global rather than per table: every reference that
    # rests on a key has to be gone before any key moves, because one table's
    # child is another's parent.
    for table, columns, target, _declared, _ondelete in DROPPED:
        name = _constraint_name(table, columns, target)
        if name:
            op.drop_constraint(name, table, type_="foreignkey")
    for name, table, columns, unique in INDEX_DROPS:
        op.execute(f'DROP INDEX IF EXISTS "{name}"')
    for table in SCOPED:
        op.execute(f'ALTER TABLE "{table}" DROP CONSTRAINT "{table}_pkey"')
        op.create_primary_key(f"{table}_pkey", table, ["tenant_id", "id"])
    for table, columns, target, target_columns, ondelete, name in REFERENCES:
        op.create_foreign_key(
            name or None,
            table,
            target,
            list(columns),
            list(target_columns),
            ondelete=ondelete or None,
        )
    for name, table, columns, unique in INDEX_CREATES:
        op.create_index(name, table, list(columns), unique=unique)


def downgrade() -> None:
    """Put the narrower key back, and let PostgreSQL refuse if it no longer fits.

    Going back is only possible while no two companies have drawn the same
    identity, because the old key was `id` alone. Every identity here is random,
    so no database holds such a pair today — and if one ever did, the key below
    would refuse to build rather than quietly lose a row, which is the behaviour
    worth keeping.
    """
    for name, table, columns, unique in reversed(INDEX_CREATES):
        op.execute(f'DROP INDEX IF EXISTS "{name}"')
    for table, columns, target, target_columns, ondelete, name in reversed(REFERENCES):
        existing = _constraint_name(table, columns, target)
        if existing:
            op.drop_constraint(existing, table, type_="foreignkey")
    for table in reversed(SCOPED):
        op.execute(f'ALTER TABLE "{table}" DROP CONSTRAINT "{table}_pkey"')
        op.create_primary_key(f"{table}_pkey", table, ["id"])
    for table, columns, target, declared, ondelete in reversed(DROPPED):
        # Under the name it had. A later revision drops some of these by name
        # and would not find them if PostgreSQL had made one up here.
        op.create_foreign_key(
            declared or None,
            table,
            target,
            list(columns),
            ["id"],
            ondelete=ondelete or None,
        )
    for name, table, columns, unique in reversed(INDEX_DROPS):
        op.create_index(name, table, list(columns), unique=unique)
